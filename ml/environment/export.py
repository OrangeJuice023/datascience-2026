"""Export weekly city weather to the hub ENVIRONMENT tab and the web app.

    python -m environment.export                       # CSV + web JSON
    python -m environment.export --hub ../DATASCIENCE_MASTER_DATA_HUB.xlsx

Writes:
  data/processed/environment/hub_environment.csv   ENVIRONMENT tab rows
  web/src/data/environment-weekly.json             columnar bundle for
                                                   web/src/lib/environment
  --hub: replaces the ENVIRONMENT tab body (rows 3+) and adds the new columns
         to DATA_DICTIONARY. Other tabs are not touched.

Rows are copied from city_weekly_weather.csv, one per geography x week x
source. Anomalies and lags are DERIVED features and stay out of ENVIRONMENT
(hub rule: TRAINING_DATA is rebuilt from source tabs).
"""

import argparse
import json
from pathlib import Path

import pandas as pd

from . import compare, geography
from .paths import OUT, REPO
from .sources import HDX_DATASETS, OPEN_METEO, WEATHER_VARIABLES

VARS = list(WEATHER_VARIABLES)
WEB_JSON = REPO / "web" / "src" / "data" / "environment-weekly.json"
HUB_COLUMNS = [
    "geography_id", "geography_name", "geographic_level", "period_start", "period_end",
    "epi_year", "epi_week", "temporal_resolution", "source_id", "upstream_product",
    "aggregation_method", *VARS, "days_observed", "qc_flag", "confidence",
    "coverage_start", "coverage_end", "grid_cell", "source_url", "retrieved_at",
    "as_of_date", "evidence_type", "is_sample", "notes",
]
HUB_PURPOSE = (
    "Weekly city weather, one row per geography x week (Sun-Sat) x source. Sources are "
    "never merged in a row; compare/harmonise only through ml/environment/features.py. "
    "Generated by `python -m environment.export --hub`; do not hand-edit. "
    "Anomalies and lags belong in TRAINING_DATA."
)
# DATA_DICTIONARY rows for columns this tab adds (column, meaning, example,
# required, allowed values, owner).
DICTIONARY = [
    ("epi_year", "MMWR epi year of the week (year of its Wednesday).", "2019", "YES (ENVIRONMENT)", "integer", "Physics 3"),
    ("epi_week", "MMWR week number, Sun-Sat weeks.", "27", "YES (ENVIRONMENT)", "1-53", "Physics 3"),
    ("source_id", "Weather source of this row; rows from different sources are never merged.",
     "cchain", "YES (ENVIRONMENT)", "cchain/open_meteo", "Physics 3"),
    ("upstream_product", "Product the source derives each variable from.", "ERA5; CHIRPS v2",
     "YES (ENVIRONMENT)", "text", "Physics 3"),
    ("aggregation_method", "How the city value was formed from grid or barangay values.",
     "population_weighted_mean_of_barangays", "YES (ENVIRONMENT)",
     "population_weighted_mean_of_barangays/single_grid_cell_at_population_weighted_centroid", "Physics 3"),
    ("precipitation_mm", "Total rainfall over the 7 days.", "84.2", "YES (ENVIRONMENT)", "mm, blank if any day missing", "Physics 3"),
    ("temperature_mean_c", "Mean of daily mean 2 m air temperature.", "27.9", "YES (ENVIRONMENT)", "degC", "Physics 3"),
    ("temperature_min_c", "Mean of daily minimum temperature.", "24.1", "YES (ENVIRONMENT)", "degC", "Physics 3"),
    ("temperature_max_c", "Mean of daily maximum temperature.", "32.4", "YES (ENVIRONMENT)", "degC", "Physics 3"),
    ("humidity_mean_pct", "Mean of daily mean relative humidity.", "81.5", "YES (ENVIRONMENT)", "%", "Physics 3"),
    ("days_observed", "Days of the week with every variable present.", "7", "YES (ENVIRONMENT)", "0-7", "Physics 3"),
    ("qc_flag", "Data-quality flags, ';'-separated.", "ok", "YES (ENVIRONMENT)",
     "ok/incomplete_week/range_check_failed/rain_partial_area/provisional_era5t", "Physics 3"),
    ("coverage_start", "First day this source has data for this geography.", "2003-01-05", "YES (ENVIRONMENT)", "YYYY-MM-DD", "Physics 3"),
    ("coverage_end", "Last day this source has data for this geography.", "2022-12-31", "YES (ENVIRONMENT)", "YYYY-MM-DD", "Physics 3"),
    ("grid_cell", "ERA5 cell centre Open-Meteo used (lat,lon); blank for area aggregates.", "7.0,125.5",
     "YES (ENVIRONMENT)", "lat,lon", "Physics 3"),
]
NOTES = {
    "cchain": "Primary source for modelling (CCHAIN cities, to 2022).",
    "open_meteo": "Extension source: after 2022 and outside CCHAIN. Rainfall is ERA5, not CHIRPS: "
                  "compare as within-source anomalies only (weather_comparability.json).",
}


def hub_rows(weather: pd.DataFrame) -> pd.DataFrame:
    df = weather.copy()
    df["as_of_date"] = pd.to_datetime(df["retrieved_at"], utc=True).dt.strftime("%Y-%m-%d")
    df["notes"] = df["source_id"].map(NOTES)
    df["is_sample"] = "FALSE"
    df[VARS] = df[VARS].round(2)
    for c in ("period_start", "period_end", "coverage_start", "coverage_end"):
        df[c] = df[c].dt.strftime("%Y-%m-%d")
    return df[HUB_COLUMNS]


def web_bundle(weather: pd.DataFrame, geo: pd.DataFrame, verdicts: dict) -> dict:
    series = []
    for (gid, sid), g in weather.groupby(["geography_id", "source_id"]):
        g = g.sort_values("period_start")
        assert (g["period_start"].diff().dropna() == pd.Timedelta(days=7)).all(), "gap in weekly grid"
        series.append({
            "geographyId": gid,
            "sourceId": sid,
            "firstPeriodStart": g["period_start"].iloc[0].strftime("%Y-%m-%d"),
            "coverageStart": g["coverage_start"].iloc[0].strftime("%Y-%m-%d"),
            "coverageEnd": g["coverage_end"].iloc[0].strftime("%Y-%m-%d"),
            "gridCell": None if g["grid_cell"].isna().all() else g["grid_cell"].dropna().iloc[0],
            "values": {v: [None if pd.isna(x) else round(float(x), 2) for x in g[v]] for v in VARS},
            "daysObserved": g["days_observed"].astype(int).tolist(),
            "qcFlags": ["" if f == "ok" else f for f in g["qc_flag"]],
            "confidence": [c[0] for c in g["confidence"]],  # H / M / L
        })
    meta = weather.drop_duplicates("source_id").set_index("source_id")
    return {
        "generatedBy": "ml/environment/export.py",
        "weekConvention": "Sun-Sat weeks keyed by periodStart (Sunday); MMWR epi weeks",
        "variables": {v: spec["unit"] for v, spec in WEATHER_VARIABLES.items()},
        "sources": {
            "cchain": {
                "name": "Project CCHAIN climate_atmosphere",
                "upstreamProduct": meta.loc["cchain", "upstream_product"],
                "aggregationMethod": meta.loc["cchain", "aggregation_method"],
                "url": meta.loc["cchain", "source_url"],
                "retrievedAt": meta.loc["cchain", "retrieved_at"],
                "license": HDX_DATASETS["cchain"]["license"],
                "attribution": HDX_DATASETS["cchain"]["attribution"],
            },
            "open_meteo": {
                "name": "Open-Meteo Historical Weather API (ERA5)",
                "upstreamProduct": meta.loc["open_meteo", "upstream_product"],
                "aggregationMethod": meta.loc["open_meteo", "aggregation_method"],
                "url": meta.loc["open_meteo", "source_url"],
                "retrievedAt": weather.loc[weather["source_id"] == "open_meteo", "retrieved_at"].max(),
                "license": OPEN_METEO["license"],
                "attribution": OPEN_METEO["attribution"],
            },
        },
        "geographies": [
            {"id": r.geography_id, "name": r.geography_name, "level": r.geographic_level,
             "latitude": r.latitude, "longitude": r.longitude, "inCchain": bool(r.in_cchain)}
            for r in geo.itertuples()
        ],
        "comparability": {v: d["verdict"] for v, d in verdicts.items()},
        "series": series,
    }


def write_hub(path: Path, rows: pd.DataFrame) -> None:
    import openpyxl

    wb = openpyxl.load_workbook(path)
    ws = wb["ENVIRONMENT"]
    ws.delete_rows(3, ws.max_row)
    ws["A2"] = HUB_PURPOSE
    ws.append(HUB_COLUMNS)
    for rec in rows.itertuples(index=False):
        ws.append([None if pd.isna(x) else x for x in rec])
    ws.freeze_panes = "A4"

    dd = wb["DATA_DICTIONARY"]
    existing = {dd.cell(r, 1).value for r in range(4, dd.max_row + 1)}
    for entry in DICTIONARY:
        if entry[0] not in existing:
            dd.append(list(entry))
    wb.save(path)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--hub", type=Path, help="path to DATASCIENCE_MASTER_DATA_HUB.xlsx")
    args = parser.parse_args()

    weather = compare.load()
    geo = geography.load()
    verdicts = json.loads((OUT / "weather_comparability.json").read_text())["verdicts_modeling_cities"]

    rows = hub_rows(weather)
    rows.to_csv(OUT / "hub_environment.csv", index=False, float_format="%.3f")
    WEB_JSON.write_text(json.dumps(web_bundle(weather, geo, verdicts), separators=(",", ":")) + "\n")
    print(f"{len(rows)} ENVIRONMENT rows; wrote {WEB_JSON.relative_to(REPO)} "
          f"({WEB_JSON.stat().st_size / 1e6:.1f} MB)")
    if args.hub:
        write_hub(args.hub, rows)
        print(f"updated ENVIRONMENT and DATA_DICTIONARY in {args.hub}")


if __name__ == "__main__":
    main()
