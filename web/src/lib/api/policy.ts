import type { PolicyInfoData } from "@sigma/contracts";
import { getAllPolicyEvidence, POLICY_RESEARCH_PACK } from "@/data/policy-evidence";
import { SIGMA_DOES_NOT } from "@/data/sigma-scope";
import { isLocalPolicyFor } from "@/lib/analyze-chat/evidence";
import type { SigmaData } from "@/lib/sigma/data";
import { buildSources } from "./sources";

/**
 * Policy service layer.
 *
 * GET /api/v1/policy/info: what policy evidence SIGMA holds and where SIGI
 * can answer, counted from the policy evidence registry and the 126 HDX
 * reporting units rather than typed in. SIGI's answers are never a verified
 * government position, and the disclosure travels in the payload so a
 * client cannot drop it.
 */

export const POLICY_AI_DISCLOSURE =
  "SIGI's answers are generated by a language model from SIGMA's records for one reporting unit. They can be wrong, are not a verified government position or an official advisory, and are not clinical or legal advice: check every cited source before using an answer.";

export const POLICY_SOURCE = "SIGMA policy evidence registry and the 126 HDX dengue reporting units";

export const POLICY_SOURCE_NOTE =
  "Policy records are cited extracts from official LGU and national documents, each with its verification status. A local record applies only to the place it names; national records apply to every unit but are not findings about any one place.";

export function buildPolicyInfo(sigma: SigmaData): PolicyInfoData {
  const records = getAllPolicyEvidence();
  const national = records.filter((r) => r.locationId === null);
  const localPlaces = [...new Set(records.filter((r) => r.locationId !== null).map((r) => r.entityName))];
  const count = (status: string) => records.filter((r) => r.verificationStatus === status).length;
  const needsReview = count("needs_review");

  const areas = sigma.units
    .map((u) => ({
      id: u.id,
      name: u.name,
      unitType: u.unitType,
      region: u.region,
      hasLocalPolicy: records.some((r) => isLocalPolicyFor(r.locationId, u.id)),
    }))
    .sort((a, b) => a.name.localeCompare(b.name));

  return {
    scope: {
      isSample: false,
      source: POLICY_SOURCE,
      sourceNote: POLICY_SOURCE_NOTE,
      aiDisclosure: POLICY_AI_DISCLOSURE,
    },
    evidenceSummary: [
      `${records.length} policy evidence records: ${count("verified")} verified, ${count("partially_verified")} partially verified${needsReview ? `, ${needsReview} needing review` : ""}.`,
      `${national.length} national records (laws and DOH and DILG issuances) apply to every reporting unit.`,
      `Local records cover ${localPlaces.join(", ")}.`,
      "Every record cites the document it comes from and says what that document does and does not establish.",
    ],
    whatSigmaDoesNot: [...SIGMA_DOES_NOT],
    supportedDiseases: ["Dengue"],
    chatScope: [{ disease: "Dengue", locationIds: areas.map((a) => a.id) }],
    areas,
    sources: buildSources(),
    limitations: [...POLICY_RESEARCH_PACK.limitations],
  };
}
