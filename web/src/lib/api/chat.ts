import type { ChatMessage, ChatResponseData } from "@sigma/contracts";
import {
  buildPolicyChatContext,
  getSupportedLguIdsForDisease,
  isValidDisease,
  isValidLgu,
} from "@/lib/policy-chat/context";
import { buildSystemPrompt } from "@/lib/policy-chat/system-prompt";
import { ApiError } from "./envelope";
import { LIMITS } from "./query";

/**
 * Chat service layer.
 *
 * The model is an assistant over evidence, never an authority. The service
 * therefore:
 * - refuses to answer when no provider is configured, instead of returning a
 *   canned reply that could be mistaken for a real answer;
 * - bounds the request (message length, history depth, tokens);
 * - never forwards upstream error text to the client;
 * - states in every response what context the model actually received.
 */

const GROQ_ENDPOINT = "https://api.groq.com/openai/v1/chat/completions";
const DEFAULT_MODEL = "openai/gpt-oss-20b";

export const CHAT_LIMITATIONS = [
  "The reply is generated by a language model over demo evidence and can be wrong.",
  "It is not a verified government position and not an official advisory.",
  "It does not confirm outbreaks, diagnose patients, or prescribe policy.",
  "The underlying signals, trends and facility figures are simulated.",
];

export interface ParsedChatRequest {
  message: string;
  history: ChatMessage[];
  disease: string;
  locationId: string;
}

function isString(value: unknown): value is string {
  return typeof value === "string";
}

function normalizeMessage(value: unknown): ChatMessage | null {
  if (!value || typeof value !== "object") return null;
  const obj = value as Record<string, unknown>;
  const role = obj.role;
  const content = obj.content;
  if ((role !== "user" && role !== "assistant") || !isString(content)) return null;
  return { role, content: content.slice(0, LIMITS.maxMessageLength) };
}

/** Validates the request body and the disease/LGU pairing. */
export function parseChatRequest(body: unknown): ParsedChatRequest {
  if (!body || typeof body !== "object") {
    throw ApiError.badRequest("A JSON object body is required.");
  }
  const raw = body as Record<string, unknown>;

  const message = isString(raw.message) ? raw.message.trim() : "";
  if (!message) {
    throw ApiError.badRequest("A non-empty \"message\" is required.", { message: ["required"] });
  }
  if (message.length > LIMITS.maxMessageLength) {
    throw ApiError.badRequest(`"message" must be at most ${LIMITS.maxMessageLength} characters.`, {
      message: [`at most ${LIMITS.maxMessageLength} characters`],
    });
  }

  const disease = isString(raw.disease) ? raw.disease : "";
  if (!disease || !isValidDisease(disease)) {
    throw ApiError.badRequest("\"disease\" must be a supported disease.", {
      disease: ["unsupported disease"],
    });
  }

  const locationId = isString(raw.locationId) ? raw.locationId : "";
  if (!locationId || !isValidLgu(locationId)) {
    throw ApiError.badRequest("\"locationId\" must be a known LGU.", {
      locationId: ["unknown LGU"],
    });
  }
  if (!getSupportedLguIdsForDisease(disease).includes(locationId)) {
    throw ApiError.badRequest("No data exists for this disease and LGU combination.", {
      locationId: ["no data for this disease"],
    });
  }

  const history = Array.isArray(raw.history)
    ? raw.history.map(normalizeMessage).filter((m): m is ChatMessage => m !== null)
    : [];

  return {
    message: message.slice(0, LIMITS.maxMessageLength),
    history: history.slice(-LIMITS.maxHistory),
    disease,
    locationId,
  };
}

export interface ChatProviderConfig {
  apiKey: string | undefined;
  model: string | undefined;
}

export function resolveModel(config: ChatProviderConfig): string {
  const configured = config.model?.trim();
  return configured ? configured : DEFAULT_MODEL;
}

export interface CompleteChatInput {
  request: ParsedChatRequest;
  config: ChatProviderConfig;
}

export async function completeChat(input: CompleteChatInput): Promise<ChatResponseData> {
  const { apiKey } = input.config;
  if (!apiKey) {
    throw ApiError.notConfigured(
      "The Policy Copilot has no model provider configured, so it cannot answer. Nothing is returned in place of a real answer.",
    );
  }

  const context = await buildPolicyChatContext(input.request.disease, input.request.locationId);
  const model = resolveModel(input.config);

  const messages = [
    { role: "system" as const, content: buildSystemPrompt(context) },
    ...input.request.history,
    { role: "user" as const, content: input.request.message },
  ];

  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), LIMITS.requestTimeoutMs);

  let upstream: Response;
  try {
    upstream = await fetch(GROQ_ENDPOINT, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        Authorization: `Bearer ${apiKey}`,
      },
      body: JSON.stringify({
        model,
        messages,
        max_completion_tokens: LIMITS.maxCompletionTokens,
        temperature: 0.3,
      }),
      signal: controller.signal,
    });
  } catch (error) {
    if (error instanceof DOMException && error.name === "AbortError") {
      throw new ApiError("upstream_unavailable", 504, "The model provider request timed out.");
    }
    throw ApiError.upstreamUnavailable("The model provider could not be reached.");
  } finally {
    clearTimeout(timer);
  }

  if (upstream.status === 429) {
    throw ApiError.rateLimited("The model provider rate limit was reached. Try again shortly.", 30);
  }
  if (!upstream.ok) {
    throw ApiError.upstreamUnavailable("The model provider request failed.");
  }

  let payload: {
    choices?: Array<{ message?: { content?: string | null } }>;
    error?: { message?: string };
  };
  try {
    payload = (await upstream.json()) as typeof payload;
  } catch {
    throw ApiError.upstreamUnavailable("The model provider returned a malformed response.");
  }

  if (payload.error?.message) {
    throw ApiError.upstreamUnavailable("The model provider request failed.");
  }

  const content = payload.choices?.[0]?.message?.content;
  if (!isString(content) || !content.trim()) {
    throw ApiError.upstreamUnavailable("The model provider returned an empty response.");
  }

  return {
    reply: content,
    model,
    contextScope: `Demo evidence for ${input.request.disease} in ${context.lgu?.name ?? input.request.locationId}, plus the source catalogue and stated limitations.`,
    limitations: [...CHAT_LIMITATIONS],
  };
}
