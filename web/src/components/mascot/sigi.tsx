"use client";

import Image from "next/image";
import { useSyncExternalStore } from "react";

import type { SigiState } from "@sigma/contracts";

/**
 * Sigi, the SIGMA companion.
 *
 * The mascot is an interface affordance, not an indicator of what the data
 * means. Its animation says what the client is doing — waiting, listening,
 * working, showing a result — and never whether an outbreak is happening.
 * The data state is always stated in words next to it.
 *
 * Two rules are enforced here:
 * - A reader who asks for reduced motion gets the still frame, so nothing
 *   animates on a device that has asked the system to stop motion.
 * - Every state is bundled locally: the animations are generated by
 *   `web/scripts/generate-sigi-mascot.py` and served from `public/mascot`.
 */

const SOURCES: Record<SigiState, { animated: string; still: string }> = {
  idle: { animated: "/mascot/sigi/idle.gif", still: "/mascot/sigi/idle.png" },
  greeting: { animated: "/mascot/sigi/greeting.gif", still: "/mascot/sigi/greeting.png" },
  listening: { animated: "/mascot/sigi/listening.gif", still: "/mascot/sigi/listening.png" },
  thinking: { animated: "/mascot/sigi/thinking.gif", still: "/mascot/sigi/thinking.png" },
  responding: { animated: "/mascot/sigi/responding.gif", still: "/mascot/sigi/responding.png" },
  insight: { animated: "/mascot/sigi/insight.gif", still: "/mascot/sigi/insight.png" },
  unavailable: { animated: "/mascot/sigi/unavailable.gif", still: "/mascot/sigi/unavailable.png" },
  error: { animated: "/mascot/sigi/error.gif", still: "/mascot/sigi/error.png" },
  success: { animated: "/mascot/sigi/success.gif", still: "/mascot/sigi/success.png" },
};

const STATE_PURPOSE: Record<SigiState, string> = {
  idle: "waiting",
  greeting: "greeting",
  listening: "listening",
  thinking: "working on it",
  responding: "showing a result",
  insight: "showing a result",
  unavailable: "not connected to a source",
  error: "reporting a failure",
  success: "reporting a completed action",
};

/** Tracks the operating-system "reduce motion" setting. */
export function usePrefersReducedMotion(): boolean {
  return useSyncExternalStore(
    (onChange) => {
      const query = window.matchMedia("(prefers-reduced-motion: reduce)");
      query.addEventListener("change", onChange);
      return () => query.removeEventListener("change", onChange);
    },
    () => window.matchMedia("(prefers-reduced-motion: reduce)").matches,
    () => false,
  );
}

export interface SigiProps {
  /** What the client is doing right now. Never a data condition. */
  state?: SigiState;
  /** Rendered size in pixels; the artwork is 128×128. */
  size?: number;
  className?: string;
  /**
   * Accessible description. Defaults to the state's purpose, which describes
   * the interface and not the data.
   */
  label?: string;
}

export function Sigi({ state = "idle", size = 64, className, label }: SigiProps) {
  const reducedMotion = usePrefersReducedMotion();
  const source = reducedMotion ? SOURCES[state].still : SOURCES[state].animated;
  const description = label ?? `Sigi, the SIGMA companion, ${STATE_PURPOSE[state]}`;

  return (
    <Image
      src={source}
      alt={description}
      width={size}
      height={size}
      unoptimized
      draggable={false}
      className={className}
      style={{ width: size, height: size }}
    />
  );
}

/**
 * Picks the mascot state for a data status.
 *
 * The mapping is deliberately conservative: a source that is not connected
 * gets the puzzled pose, a failed request gets the concerned pose, and only a
 * result that actually came back gets the "insight" pose. Nothing here ever
 * claims that a condition was detected.
 */
export function sigiStateForData(input: {
  loading?: boolean;
  failed?: boolean;
  connected?: boolean;
  hasResult?: boolean;
}): SigiState {
  if (input.failed) return "error";
  if (input.loading) return "thinking";
  if (input.connected === false) return "unavailable";
  if (input.hasResult) return "insight";
  return "idle";
}
